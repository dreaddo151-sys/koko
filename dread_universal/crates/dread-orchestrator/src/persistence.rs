/// Result of the atomic local dispatch preparation. `Existing` is an
/// idempotent replay and must never cause the API to submit another provider
/// start request. Only `Created` authorizes the first start attempt.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DispatchPreparation {
    Created(AttemptRecord),
    Existing(AttemptRecord),
}

impl DispatchPreparation {
    pub fn attempt(&self) -> &AttemptRecord {
        match self {
            Self::Created(attempt) | Self::Existing(attempt) => attempt,
        }
    }

    pub const fn is_new(&self) -> bool {
        matches!(self, Self::Created(_))
    }
}

