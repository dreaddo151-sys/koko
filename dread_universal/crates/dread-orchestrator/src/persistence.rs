/// Only application-internal trusted components implement this trait.
/// Implementations must consult the authoritative provider adapter registry,
/// canonical capability records/revisions, signed or authenticated isolation
/// evidence, and the policy engine. A caller-provided `true` flag or hash is
/// explicitly insufficient.
pub trait ExecutionAuthority: Send + Sync {
    fn authorize_dispatch(
        &self,
        connection: &Connection,
        request: &DispatchRequest,
        now: i64,
    ) -> Result<AuthorizationFacts, String>;

    /// Re-check current enablement/revocation and both registration revisions
    /// while the dispatch transaction is open, immediately before consumption.
    fn revalidate_dispatch(
        &self,
        connection: &Connection,
        admission: &AdmissionRecord,
        now: i64,
    ) -> Result<(), String>;

    /// Verify an exact provider receipt against request, attempt, adapter,
    /// provider execution ID, signature/authenticated transport, and expiry.
    fn verify_provider_evidence(
        &self,
        connection: &Connection,
        attempt: &AttemptRecord,
        evidence: &ProviderEvidence,
        now: i64,
    ) -> Result<(), String>;

    /// Authenticate and scope a provider event before it enters the canonical
    /// task event stream. Event identity is separately deduplicated in SQLite.
    fn verify_provider_event(
        &self,
        connection: &Connection,
        attempt: &AttemptRecord,
        external_event_id: &str,
        event_type: &str,
        payload_json: &str,
        now: i64,
    ) -> Result<(), String>;

    /// New signed-event path. Legacy authorities retain their old behavior;
    /// the production Phase 6 authority requires and verifies the receipt.
    fn verify_provider_event_receipt(
        &self,
        connection: &Connection,
        attempt: &AttemptRecord,
        event: &ProviderEventReceiptContext<'_>,
    ) -> Result<(), String> {
        self.verify_provider_event(
            connection,
            attempt,
            event.external_event_id,
            event.event_type,
            event.payload_json,
            event.now,
        )
    }

    /// Independently verify the provider's claimed result. The verifier must
    /// be a separate trusted component/identity from the original requester.
    fn verify_independent_result(
        &self,
        connection: &Connection,
        attempt: &AttemptRecord,
        result_json: Option<&str>,
        provider_error: Option<&str>,
        now: i64,
    ) -> Result<VerificationFacts, String>;

    /// Validate the provider's current idempotency/retry contract. This must
    /// consult current revocation and provenance, not merely cached booleans.
    fn verify_retry_contract_for_retry(
        &self,
        connection: &Connection,
        attempt: &AttemptRecord,
        now: i64,
    ) -> Result<CurrentRetryContractFacts, String>;
}

