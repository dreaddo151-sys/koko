use anyhow::{Context, Result, ensure};
use reqwest::Url;
use serde_json::Value;
use std::time::Duration;

#[derive(Clone)]
pub struct GpuSupervisorClient {
    base_url: String,
    token: String,
    http: reqwest::Client,
}

impl GpuSupervisorClient {
    pub fn new(base_url: impl AsRef<str>, token: impl Into<String>) -> Result<Self> {
        let url = Url::parse(base_url.as_ref()).context("Invalid GPU Supervisor bridge URL")?;
        ensure!(
            url.scheme() == "http"
                && matches!(url.host_str(), Some("127.0.0.1" | "localhost" | "::1"))
                && url.port().is_some()
                && url.username().is_empty()
                && url.password().is_none()
                && url.path() == "/"
                && url.query().is_none()
                && url.fragment().is_none(),
            "GPU Supervisor bridge must be explicit-port loopback HTTP"
        );
        let token = token.into();
        ensure!(
            token.len() >= 32 && token.trim() == token,
            "GPU Supervisor bridge token must be at least 32 characters"
        );
        let http = reqwest::Client::builder()
            .redirect(reqwest::redirect::Policy::none())
            .connect_timeout(Duration::from_secs(3))
            .timeout(Duration::from_secs(10))
            .build()
            .context("Could not create GPU Supervisor HTTP client")?;
        Ok(Self {
            base_url: base_url.as_ref().trim_end_matches('/').to_string(),
            token,
            http,
        })
    }

    pub async fn is_online(&self) -> Result<bool> {
        let mut response = self
            .http
            .get(format!("{}/health", self.base_url))
            .timeout(Duration::from_secs(2))
            .send()
            .await
            .context("GPU Supervisor bridge health request failed")?;
        if !response.status().is_success()
            || response
                .content_length()
                .is_some_and(|length| length > 16_384)
        {
            return Ok(false);
        }
        let mut body = Vec::new();
        while let Some(chunk) = response
            .chunk()
            .await
            .context("Could not read GPU Supervisor bridge health response")?
        {
            if body.len().saturating_add(chunk.len()) > 16_384 {
                return Ok(false);
            }
            body.extend_from_slice(&chunk);
        }
        let health: Value = serde_json::from_slice(&body)
            .context("GPU Supervisor bridge returned invalid health JSON")?;
        Ok(health.get("status").and_then(Value::as_str) == Some("ok")
            && health.get("supervisor").and_then(Value::as_str) == Some("configured"))
    }

    /// Fetch read-only hardware telemetry generated by the Python GPU Supervisor.
    /// This endpoint does not acquire, release or otherwise mutate a GPU lease.
    pub async fn telemetry(&self) -> Result<Value> {
        let mut response = self
            .http
            .get(format!("{}/v1/telemetry", self.base_url))
            .bearer_auth(&self.token)
            .timeout(Duration::from_secs(4))
            .send()
            .await
            .context("Python GPU Supervisor telemetry request failed")?;
        let status = response.status();
        if response
            .content_length()
            .is_some_and(|length| length > 1_048_576)
        {
            anyhow::bail!("GPU telemetry response exceeds the 1 MiB limit");
        }
        let mut body = Vec::new();
        while let Some(chunk) = response
            .chunk()
            .await
            .context("Could not read GPU telemetry response")?
        {
            ensure!(
                body.len().saturating_add(chunk.len()) <= 1_048_576,
                "GPU telemetry response exceeds the 1 MiB limit"
            );
            body.extend_from_slice(&chunk);
        }
        if !status.is_success() {
            anyhow::bail!("GPU Supervisor telemetry returned HTTP {}", status.as_u16());
        }
        serde_json::from_slice(&body).context("GPU Supervisor returned invalid telemetry JSON")
    }

    // The Python bridge owns the GPU lease. Rust only submits authenticated work.
    pub async fn chat_completion(&self, payload: &Value) -> Result<Value> {
        let body = serde_json::to_vec(payload).context("Could not encode GPU chat payload")?;
        ensure!(
            body.len() <= 1_048_576,
            "GPU chat request exceeds the 1 MiB Supervisor bridge limit"
        );
        let mut response = self
            .http
            .post(format!("{}/v1/chat/completions", self.base_url))
            .bearer_auth(&self.token)
            .header(reqwest::header::CONTENT_TYPE, "application/json")
            .timeout(Duration::from_secs(1805))
            .body(body)
            .send()
            .await
            .context("Python GPU Supervisor bridge request failed")?;
        let status = response.status();
        if response
            .content_length()
            .is_some_and(|length| length > 1_048_576)
        {
            anyhow::bail!("GPU Supervisor response exceeds the 1 MiB result limit");
        }
        let mut response_body = Vec::new();
        while let Some(chunk) = response
            .chunk()
            .await
            .context("Could not read GPU Supervisor response")?
        {
            ensure!(
                response_body.len().saturating_add(chunk.len()) <= 1_048_576,
                "GPU Supervisor response exceeds the 1 MiB result limit"
            );
            response_body.extend_from_slice(&chunk);
        }
        if !status.is_success() {
            anyhow::bail!(
                "GPU Supervisor returned HTTP {}: {}",
                status.as_u16(),
                String::from_utf8_lossy(&response_body)
            );
        }
        serde_json::from_slice(&response_body).context("GPU Supervisor returned invalid JSON")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use axum::{
        Json, Router,
        http::{HeaderMap, StatusCode, header::AUTHORIZATION},
        routing::{get, post},
    };
    use serde_json::{Value, json};
    use tokio::net::TcpListener;

    async fn telemetry(headers: HeaderMap) -> Json<Value> {
        assert_eq!(
            headers
                .get(AUTHORIZATION)
                .and_then(|value| value.to_str().ok()),
            Some("Bearer test-supervisor-token-that-is-long-enough")
        );
        Json(json!({
            "read_only": true,
            "devices": [{"index": 0, "name": "NVIDIA GeForce RTX 3090", "utilization_percent": 12.0}]
        }))
    }

    async fn completion(
        headers: HeaderMap,
        Json(payload): Json<Value>,
    ) -> (StatusCode, Json<Value>) {
        assert_eq!(
            headers
                .get(AUTHORIZATION)
                .and_then(|value| value.to_str().ok()),
            Some("Bearer test-supervisor-token-that-is-long-enough")
        );
        (StatusCode::OK, Json(json!({"received": payload})))
    }

    #[tokio::test]
    async fn bridge_client_sends_authenticated_chat_without_lease_endpoints() {
        let app = Router::new()
            .route(
                "/health",
                axum::routing::get(|| async {
                    Json(json!({"status": "ok", "supervisor": "configured"}))
                }),
            )
            .route("/v1/chat/completions", post(completion))
            .route("/v1/telemetry", get(telemetry));
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let server = tokio::spawn(async move {
            axum::serve(listener, app).await.unwrap();
        });
        let client = GpuSupervisorClient::new(
            format!("http://{address}"),
            "test-supervisor-token-that-is-long-enough",
        )
        .unwrap();
        let result = client
            .chat_completion(&json!({
                "model": "qwen3.8:27b",
                "messages": [{"role": "user", "content": "hello"}],
                "stream": false
            }))
            .await
            .unwrap();
        assert_eq!(result["received"]["model"], "qwen3.8:27b");
        assert!(client.is_online().await.unwrap());
        server.abort();
    }

    #[tokio::test]
    async fn telemetry_uses_authenticated_read_only_supervisor_endpoint() {
        let app = Router::new().route("/v1/telemetry", get(telemetry));
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let address = listener.local_addr().unwrap();
        let server = tokio::spawn(async move {
            axum::serve(listener, app).await.unwrap();
        });
        let client = GpuSupervisorClient::new(
            format!("http://{address}"),
            "test-supervisor-token-that-is-long-enough",
        )
        .unwrap();
        let value = client.telemetry().await.unwrap();
        assert_eq!(value["read_only"], true);
        assert_eq!(value["devices"][0]["utilization_percent"], 12.0);
        server.abort();
    }

    #[test]
    fn supervisor_client_rejects_remote_urls_and_short_tokens() {
        assert!(
            GpuSupervisorClient::new(
                "http://192.168.1.5:11502",
                "test-supervisor-token-that-is-long-enough"
            )
            .is_err()
        );
        assert!(GpuSupervisorClient::new("http://127.0.0.1:11502", "short").is_err());
    }
}
